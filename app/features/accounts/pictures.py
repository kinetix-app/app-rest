"""Owned private profile pictures; external I/O is outside database transactions."""

import asyncio
import warnings
from io import BytesIO
from uuid import uuid4

from azure.core.exceptions import AzureError, ResourceNotFoundError
from PIL import Image, ImageOps
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.storage.azure import BlobStorage
from app.features.accounts.errors import (
    InvalidPicture,
    PictureMissing,
    PictureStorageUnavailable,
    PictureTooLarge,
    UnsupportedPicture,
)
from app.features.accounts.models import Profile, User
from app.features.accounts.schemas import AccountResponse
from app.features.accounts.service import AccountDenied, read_account, require_active

MAX_PICTURE_BYTES = 5 * 1024 * 1024
PICTURE_PATH = "/api/v1/me/profile/picture"
PICTURE_TYPES = {"image/jpeg": "JPEG", "image/png": "PNG", "image/webp": "WEBP"}
_STORAGE_ERRORS = (AzureError, TimeoutError, OSError, ValueError)


def normalize_picture(data: bytes, content_type: str | None) -> bytes:
    """Decode at most 16MP, orient, resize to 1024px and discard all metadata."""
    if len(data) > MAX_PICTURE_BYTES:
        raise PictureTooLarge
    if content_type not in PICTURE_TYPES:
        raise UnsupportedPicture
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(BytesIO(data)) as source:
                if source.format != PICTURE_TYPES[content_type]:
                    raise UnsupportedPicture
                if source.width * source.height > 16_000_000 or max(source.size) > 16384:
                    raise InvalidPicture
                source.load()
                oriented = ImageOps.exif_transpose(source)
                oriented.thumbnail((1024, 1024))
                # Composite transparency onto white rather than unexpected black backgrounds.
                rgba = oriented.convert("RGBA")
                clean = Image.new("RGB", rgba.size, "white")
                clean.paste(rgba, mask=rgba.getchannel("A"))
                output = BytesIO()
                clean.save(output, format="JPEG", quality=85)
                return output.getvalue()
    except (
        OSError,
        ValueError,
        Image.DecompressionBombError,
        Image.DecompressionBombWarning,
    ):
        raise InvalidPicture from None


async def cleanup_picture(storage: BlobStorage | None, name: str | None, user_id: int) -> None:
    # Only delete names generated by this service for this authenticated account.
    if storage is None or name is None or not name.startswith(f"profiles/{user_id}/"):
        return
    try:
        await storage.delete_profile_picture(name)
    except _STORAGE_ERRORS:
        # Cleanup failure must not undo an already committed replacement/removal.
        pass


async def _set_picture(
    session: AsyncSession, user_id: int, name: str | None
) -> tuple[AccountResponse, str | None]:
    try:
        user = await session.scalar(select(User).where(User.id == user_id).with_for_update())
        if user is None:
            raise AccountDenied
        require_active(user)
        profile = await session.get(Profile, user_id)
        if profile is None:
            raise RuntimeError("Account profile is missing")
        previous = profile.picture_blob_name
        profile.picture_blob_name = name
        profile.picture_url = PICTURE_PATH if name else None
        await session.flush()
        await session.refresh(profile)
        response = await read_account(session, user_id)
        await session.commit()
        return response, previous
    except BaseException:
        await session.rollback()
        raise


async def upload_picture(
    session: AsyncSession, user_id: int, storage: BlobStorage, data: bytes, content_type: str | None
) -> AccountResponse:
    # CurrentUser finishes provisioning before reaching this use case.
    normalized = await asyncio.to_thread(normalize_picture, data, content_type)
    name = f"profiles/{user_id}/{uuid4().hex}.jpg"
    try:
        await storage.upload_profile_picture(name, normalized)
    except _STORAGE_ERRORS:
        await cleanup_picture(storage, name, user_id)
        raise PictureStorageUnavailable from None
    try:
        response, previous = await _set_picture(session, user_id, name)
    except BaseException:
        await cleanup_picture(storage, name, user_id)
        raise
    await cleanup_picture(storage, previous, user_id)
    return response


async def remove_picture(
    session: AsyncSession, user_id: int, storage: BlobStorage | None
) -> AccountResponse:
    response, previous = await _set_picture(session, user_id, None)
    await cleanup_picture(storage, previous, user_id)
    return response


async def read_picture(session: AsyncSession, user_id: int, storage: BlobStorage) -> bytes:
    try:
        user = await session.get(User, user_id, populate_existing=True)
        if user is None:
            raise AccountDenied
        require_active(user)
        profile = await session.get(Profile, user_id)
        name = profile.picture_blob_name if profile else None
        await session.commit()
    except BaseException:
        await session.rollback()
        raise
    if name is None or not name.startswith(f"profiles/{user_id}/"):
        raise PictureMissing
    try:
        return await storage.read_profile_picture(name)
    except ResourceNotFoundError:
        raise PictureMissing from None
    except _STORAGE_ERRORS:
        raise PictureStorageUnavailable from None
