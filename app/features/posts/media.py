"""Post image limits, normalization and best-effort blob cleanup."""

from azure.core.exceptions import AzureError

from app.core.storage.azure import BlobStorage
from app.features.accounts.pictures import MAX_PICTURE_BYTES, normalize_picture

POSTS_PATH = "/api/v1/posts"
MAX_POST_IMAGES = 5
MAX_POST_IMAGE_BYTES = MAX_PICTURE_BYTES
POST_IMAGE_MAX_SIDE = 1440
# All images at their limit plus bounded multipart headers and text fields.
MAX_POST_REQUEST_BYTES = MAX_POST_IMAGES * MAX_POST_IMAGE_BYTES + 64 * 1024
POST_REQUEST_LIMIT_DETAIL = "Post upload exceeds 25 MiB limit"
STORAGE_ERRORS = (AzureError, TimeoutError, OSError, ValueError)


def blob_prefix(user_id: int) -> str:
    return f"posts/{user_id}/"


def normalize_post_image(data: bytes, content_type: str | None) -> bytes:
    """Validate like profile pictures, keep up to 1440px and strip all metadata."""
    return normalize_picture(data, content_type, max_side=POST_IMAGE_MAX_SIDE)


async def cleanup_media(storage: BlobStorage | None, names: list[str], user_id: int) -> None:
    # Only delete names generated by this service for this account.
    if storage is None:
        return
    for name in names:
        if not name.startswith(blob_prefix(user_id)):
            continue
        try:
            await storage.delete_post_media(name)
        except STORAGE_ERRORS:
            # Cleanup failure must not undo an already committed change.
            pass
