-- Training section
-- Available sports and physical activity types
CREATE TABLE sport (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

-- Exercise catalog, associated with a sport
CREATE TABLE exercise (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT,
    sport_id BIGINT NOT NULL REFERENCES sport(id),
    name VARCHAR(150) NOT NULL,
    description TEXT,
    muscle_group VARCHAR(100),
    video_url TEXT
);

-- Training routines, created by users or generated by AI
CREATE TABLE routine (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Exercises included in a routine, with their planned sets, reps and other parameters
CREATE TABLE routine_exercise (
    id BIGSERIAL PRIMARY KEY,
    routine_id BIGINT NOT NULL REFERENCES routine(id),
    exercise_id BIGINT NOT NULL REFERENCES exercise(id),
    exercise_order INTEGER NOT NULL,
    sets INTEGER,
    reps INTEGER,
    weight_kg DECIMAL(8,2),
    duration_seconds INTEGER,
    distance_km DECIMAL(8,2)
);

